package shellint

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"codecombo/server/config"
)

// SetupResult shell integration 启动配置
type SetupResult struct {
	Args []string // 附加到 shell 命令的参数（如 bash 的 --rcfile）
	Env  []string // 附加的环境变量（如 ZDOTDIR=...）
}

// Setup 为指定 shell 准备 shell integration 启动配置
// 不支持的 shell 返回 nil（manager 按原逻辑启动，仅无命令完成通知）
func Setup(shellPath string) (*SetupResult, error) {
	script := ScriptForShell(shellPath)
	if script == "" {
		return nil, nil
	}

	base := strings.ToLower(filepath.Base(shellPath))
	// 必须 Abs 化：脚本路径会以 -File/--rcfile 形式传给 shell 子进程，
	// 子进程 CWD 与服务进程不一定一致，相对 DataDir 会导致「脚本不存在」
	shellDir, err := filepath.Abs(filepath.Join(config.DataDir(), "shellint"))
	if err != nil {
		return nil, fmt.Errorf("resolve shellint dir: %v", err)
	}
	if err := os.MkdirAll(shellDir, 0755); err != nil {
		return nil, fmt.Errorf("create shellint dir: %v", err)
	}

	switch {
	case strings.Contains(base, "bash"):
		return setupBash(shellDir, script)
	case strings.Contains(base, "zsh"):
		return setupZsh(shellDir, script)
	case strings.Contains(base, "pwsh"), strings.Contains(base, "powershell"):
		return setupPowerShell(shellDir, script)
	default:
		return nil, nil
	}
}

// setupBash 构造 bash --rcfile <combined>，combined = source ~/.bashrc + 钩子
func setupBash(shellDir, embedded string) (*SetupResult, error) {
	rcPath := filepath.Join(shellDir, "bash.sh")
	// 注意：--rcfile 模式下 bash 不再自动 source ~/.bashrc，需要手动 source
	content := fmt.Sprintf(`# Generated by Codecombo shell integration
[ -f "$HOME/.bashrc" ] && source "$HOME/.bashrc"
[ -f "$HOME/.bash_profile" ] && source "$HOME/.bash_profile" 2>/dev/null

%s
`, embedded)
	if err := os.WriteFile(rcPath, []byte(content), 0644); err != nil {
		return nil, err
	}
	return &SetupResult{
		Args: []string{"--rcfile", rcPath},
	}, nil
}

// setupZsh 构造 ZDOTDIR=<tmpDir>，<tmpDir>/.zshrc = source ~/.zshrc + 钩子
func setupZsh(shellDir, embedded string) (*SetupResult, error) {
	zdotdir := filepath.Join(shellDir, "zsh")
	if err := os.MkdirAll(zdotdir, 0755); err != nil {
		return nil, err
	}
	rcPath := filepath.Join(zdotdir, ".zshrc")
	content := fmt.Sprintf(`# Generated by Codecombo shell integration
[ -f "$HOME/.zshrc" ] && source "$HOME/.zshrc"
[ -f "$HOME/.zshenv" ] && source "$HOME/.zshenv" 2>/dev/null

%s
`, embedded)
	if err := os.WriteFile(rcPath, []byte(content), 0644); err != nil {
		return nil, err
	}
	return &SetupResult{
		Env: []string{"ZDOTDIR=" + zdotdir},
	}, nil
}

// setupPowerShell 构造 pwsh -NoExit -File <combined>，combined = . $PROFILE + 钩子
func setupPowerShell(shellDir, embedded string) (*SetupResult, error) {
	rcPath := filepath.Join(shellDir, "powershell.ps1")
	// 注意：-File 模式下 PowerShell 不自动加载 $PROFILE
	content := fmt.Sprintf(`# Generated by Codecombo shell integration
$UserProfile = $PROFILE -replace '\.ps1$', '.ps1'
if ($UserProfile -and (Test-Path $UserProfile)) {
    try { . $UserProfile } catch {}
}

%s
`, embedded)
	// Windows PowerShell 5.1 默认按系统编码（中文 Windows 为 GB2312）读取无 BOM 的脚本，
	// 会把 UTF-8 中文注释解析成乱码导致语法错误。写入 UTF-8 BOM 强制 PS 5.1 按 UTF-8 解码。
	if err := os.WriteFile(rcPath, append([]byte{0xEF, 0xBB, 0xBF}, []byte(content)...), 0644); err != nil {
		return nil, err
	}
	return &SetupResult{
		Args: []string{"-NoExit", "-File", rcPath},
	}, nil
}
