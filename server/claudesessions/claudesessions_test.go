// P-20261031-1：纯噪声首条用户消息（整串替换符/零宽符——终端二进制输出转发
// 的实测形态）不构成标题，parseHead 继续向后找真实消息
func TestTitleSkipsNoiseOnlyTexts(t *testing.T) {
	root := t.TempDir()
	now := time.Now()
	noise := strings.Repeat("\uFFFD", 8) // 实测用户数据形态：8×U+FFFD
	var b strings.Builder
	b.WriteString(`{"parentUuid":null,"isSidechain":false,"type":"user","message":{"role":"user","content":"` + noise + `"},"timestamp":"` + now.UTC().Format(time.RFC3339) + `","cwd":"D:\p"}` + "\n")
	b.WriteString(`{"parentUuid":null,"isSidechain":false,"type":"user","message":{"role":"user","content":"修复导出乱码"},"timestamp":"` + now.UTC().Format(time.RFC3339) + `"}` + "\n")
	write(t, root, EncodePath(`D:\p`), "sess-noise", b.String(), now)

	res, err := List(root, `D:\p`, "", 10, 0)
	if err != nil {
		t.Fatal(err)
	}
	if len(res.Sessions) != 1 {
		t.Fatalf("len = %d", len(res.Sessions))
	}
	if got := res.Sessions[0].Title; got != "修复导出乱码" {
		t.Fatalf("Title = %q, want later real message", got)
	}

	// 零宽/格式符纯噪声同判（Cf 族：ZWSP/ZWNJ/BOM）
	if isTitleWorthy("\u200B\u200C\u2060\uFEFF") {
		t.Error("zero-width-only text should not be title worthy")
	}
	if isTitleWorthy("a\u0000b") == false {
		t.Error("text with visible runes around control chars should be worthy")
	}
	// 全部命中噪声时回退会话 id（恒可见，不再行失语）
	var c strings.Builder
	c.WriteString(`{"parentUuid":null,"isSidechain":false,"type":"user","message":{"role":"user","content":"` + noise + `"},"timestamp":"` + now.UTC().Format(time.RFC3339) + `","cwd":"D:\p"}` + "\n")
	write(t, root, EncodePath(`D:\p`), "sess-allnoise", c.String(), now)
	res2, err := List(root, `D:\p`, "", 10, 0)
	if err != nil {
		t.Fatal(err)
	}
	for _, s := range res2.Sessions {
		if s.ID == "sess-allnoise" && s.Title != s.ID {
			t.Fatalf("all-noise session Title = %q, want id fallback", s.Title)
		}
	}
}

// P-20261031-1：索引命中路径对「硬化前写入的噪声标题旧条目」自愈——判未命中
// 走一次重扫（换可见消息/回退 id）并 Put 覆盖，下次恢复零内容读
func TestIndexSelfHealsNoiseTitleEntries(t *testing.T) {
	root := t.TempDir()
	now := time.Now()
	noise := strings.Repeat("\uFFFD", 8)
	var b strings.Builder
	b.WriteString(`{"parentUuid":null,"isSidechain":false,"type":"user","message":{"role":"user","content":"` + noise + `"},"timestamp":"` + now.UTC().Format(time.RFC3339) + `","cwd":"D:\p"}` + "\n")
	b.WriteString(`{"parentUuid":null,"isSidechain":false,"type":"user","message":{"role":"user","content":"真实标题在此"},"timestamp":"` + now.UTC().Format(time.RFC3339) + `"}` + "\n")
	write(t, root, EncodePath(`D:\p`), "sess-heal", b.String(), now.Add(-time.Hour))

	s := store.New(filestore.New(t.TempDir()))
	ix := NewIndex(s.ClaudeIndex, root)

	// 模拟硬化前旧条目：UsageKnown/LedgerKnown 齐、mtime/size 对、标题=噪声
	st, err := os.Stat(filepath.Join(root, EncodePath(`D:\p`), "sess-heal.jsonl"))
	if err != nil {
		t.Fatal(err)
	}
	key := store.ClaudeIndexKey(root, EncodePath(`D:\p`), "sess-heal")
	if err := s.ClaudeIndex.Put(store.ClaudeIndexEntry{
		Key: key, ID: "sess-heal", Dir: EncodePath(`D:\p`), Title: noise,
		Cwd: `D:\p`, FirstAt: now.Add(-time.Hour), LastAt: now.Add(-time.Hour),
		MessageCount: 2, SizeBytes: st.Size(), MtimeNs: st.ModTime().UnixNano(),
		UsageKnown: true, LedgerKnown: true,
	}); err != nil {
		t.Fatal(err)
	}

	res, err := ix.List(`D:\p`, 10, 0)
	if err != nil {
		t.Fatal(err)
	}
	if len(res.Sessions) != 1 {
		t.Fatalf("len = %d", len(res.Sessions))
	}
	if got := res.Sessions[0].Title; got != "真实标题在此" {
		t.Fatalf("Title = %q, want self-healed real message", got)
	}
	// 自愈后条目被覆盖：再列一次直接命中（标题保持可见形态）
	res2, err := ix.List(`D:\p`, 10, 0)
	if err != nil {
		t.Fatal(err)
	}
	if res2.Sessions[0].Title != "真实标题在此" {
		t.Fatalf("second list Title = %q", res2.Sessions[0].Title)
	}
}
