// 构造一个最小可解析的 claude jsonl（字段顺序/形态与真实存储一致）
func fixtureJSONL(title string, ts time.Time, extraLines ...string) string {
	return fixtureJSONLCwd(title, ts, `D:\e2e-demo`, extraLines...)
}

func fixtureJSONLCwd(title string, ts time.Time, cwd string, extraLines ...string) string {
	var b strings.Builder
	b.WriteString(`{"type":"last-prompt","sessionId":"x"}` + "\n")
	// cwd 在 JSON 里是转义形态：Go 字符串 cwd 的每个反斜杠写作 \\（raw string 内即字面 \\）
	escapedCwd := strings.ReplaceAll(cwd, `\`, `\\`)
	b.WriteString(`{"parentUuid":null,"isSidechain":false,"type":"user","message":{"role":"user","content":"` + title + `"},"timestamp":"` + ts.UTC().Format(time.RFC3339) + `","cwd":"` + escapedCwd + `"}` + "\n")
	b.WriteString(`{"type":"assistant","message":{"role":"assistant","content":[{"type":"text","text":"ok"}]},"timestamp":"` + ts.UTC().Format(time.RFC3339) + `"}` + "\n")
	for _, l := range extraLines {
		b.WriteString(l + "\n")
	}
	return b.String()
}

func write(t *testing.T, root, encodedDir, id, content string, mod time.Time) {
	t.Helper()
	dir := filepath.Join(root, encodedDir)
	if err := os.MkdirAll(dir, 0o755); err != nil {
		t.Fatal(err)
	}
	path := filepath.Join(dir, id+".jsonl")
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := os.Chtimes(path, mod, mod); err != nil {
		t.Fatal(err)
	}
}

func TestEncodePath(t *testing.T) {
	// 夹具路径用中性用户/目录名：本测试随发布拷贝包外发，不得携带开发机
	// 真实用户名与目录拓扑（P-20261025-2 敏感扫描门禁），编码语义不受影响
	cases := map[string]string{
		`C:\Users\devone`:              "C--Users-devone",
		`D:\devtree\go\app`:            "D--devtree-go-app",
		"/root/proj":                   "-root-proj",
		`\\wsl.localhost\Ubuntu-24.04`: "--wsl.localhost-Ubuntu-24.04",
	}
	for in, want := range cases {
		if got := EncodePath(in); got != want {
			t.Errorf("EncodePath(%q) = %q, want %q", in, got, want)
		}
	}
}

func TestListProjectScopeSortAndFields(t *testing.T) {
	root := t.TempDir()
	now := time.Now()
	// 三个会话：mtime 交错写入，验证 LastAt 倒序
	write(t, root, EncodePath(`D:\e2e-demo`), "id-old", fixtureJSONL("旧会话标题", now.Add(-72*time.Hour)), now.Add(-72*time.Hour))
	write(t, root, EncodePath(`D:\e2e-demo`), "id-new", fixtureJSONL("最新会话标题", now.Add(-time.Hour)), now.Add(-time.Hour))
	write(t, root, EncodePath(`D:\e2e-demo`), "id-mid", fixtureJSONL("中间会话", now.Add(-24*time.Hour)), now.Add(-24*time.Hour))

	res, err := List(root, `D:\e2e-demo`, "", 10, 0)
	if err != nil {
		t.Fatal(err)
	}
	if res.Total != 3 {
		t.Fatalf("Total = %d, want 3", res.Total)
	}
	if res.Sessions[0].ID != "id-new" || res.Sessions[2].ID != "id-old" {
		t.Fatalf("sort by LastAt desc broken: %v, %v, %v",
			res.Sessions[0].ID, res.Sessions[1].ID, res.Sessions[2].ID)
	}
	first := res.Sessions[0]
	if first.Title != "最新会话标题" {
		t.Errorf("Title = %q", first.Title)
	}
	if first.Cwd != `D:\e2e-demo` {
		t.Errorf("Cwd = %q", first.Cwd)
	}
	if first.MessageCount != 3 {
		t.Errorf("MessageCount = %d, want 3", first.MessageCount)
	}
	if first.FirstAt.IsZero() {
		t.Error("FirstAt not parsed from timestamp")
	}
	// transcript 路径（P-20261003-215）：数据面同源派生，回放页「AI 总结」经
	// ask-agent prompt 让 agent 自读全量的锚点
	if want := filepath.Join(root, EncodePath(`D:\e2e-demo`), "id-new.jsonl"); first.TranscriptPath != want {
		t.Errorf("TranscriptPath = %q, want %q", first.TranscriptPath, want)
	}
}

// 标题提取跳过 Claude 注入的元信息块（resume caveat / local command 记录），
// 取其后第一条真实用户消息；Active 按 mtime 活跃窗口判定
func TestTitleSkipsClaudeMetaBlocks(t *testing.T) {
	root := t.TempDir()
	now := time.Now()
	var b strings.Builder
	b.WriteString(`{"type":"last-prompt","sessionId":"x"}` + "\n")
	// resume 场景首条"用户消息"是 caveat 元信息块，非真实标题
	b.WriteString(`{"parentUuid":null,"isSidechain":false,"type":"user","message":{"role":"user","content":"<local-command-caveat>Caveat: The messages below were generated by the user while running a local command. Do not do anything with this content.</local-command-caveat>"},"timestamp":"` + now.UTC().Format(time.RFC3339) + `"}` + "\n")
	b.WriteString(`{"parentUuid":null,"isSidechain":false,"type":"user","message":{"role":"user","content":"<command-name>/model</command-name><command-message>opus</command-message>"},"timestamp":"` + now.UTC().Format(time.RFC3339) + `"}` + "\n")
	b.WriteString(`{"parentUuid":null,"isSidechain":false,"type":"user","message":{"role":"user","content":"实现登录功能"},"timestamp":"` + now.UTC().Format(time.RFC3339) + `","cwd":"D:\\p"}` + "\n")
	b.WriteString(`{"type":"assistant","message":{"role":"assistant","content":[{"type":"text","text":"ok"}]},"timestamp":"` + now.UTC().Format(time.RFC3339) + `"}` + "\n")
	// mtime 刚刚 = 活跃窗口内
	write(t, root, EncodePath(`D:\p`), "sess-meta", b.String(), now)

	res, err := List(root, `D:\p`, "", 10, 0)
	if err != nil {
		t.Fatal(err)
	}
	if len(res.Sessions) != 1 {
		t.Fatalf("len = %d", len(res.Sessions))
	}
	s := res.Sessions[0]
	if s.Title != "实现登录功能" {
		t.Fatalf("Title = %q, want real user message after meta blocks", s.Title)
	}
	if !s.Active {
		t.Error("fresh mtime should mark session Active")
	}

	// mtime 远超活跃窗口：非活跃（恢复入口应可用）
	write(t, root, EncodePath(`D:\p`), "sess-old", fixtureJSONL("老会话", now.Add(-72*time.Hour)), now.Add(-72*time.Hour))
	res2, err := List(root, `D:\p`, "", 10, 0)
	if err != nil {
		t.Fatal(err)
	}
	for _, s := range res2.Sessions {
		if s.ID == "sess-old" && s.Active {
			t.Error("stale session should not be Active")
		}
		if s.ID == "sess-meta" && !s.Active {
			t.Error("fresh session should stay Active")
		}
	}
}

func TestListPagingOffsetLimit(t *testing.T) {
	root := t.TempDir()
	now := time.Now()
	for i := 0; i < 5; i++ {
		write(t, root, EncodePath(`D:\p`), string(rune('a'+i)),
			fixtureJSONL("t", now.Add(-time.Duration(i)*time.Hour)), now.Add(-time.Duration(i)*time.Hour))
	}
	res, err := List(root, `D:\p`, "", 2, 0)
	if err != nil || len(res.Sessions) != 2 || res.Total != 5 {
		t.Fatalf("page1: total=%d len=%d err=%v", res.Total, len(res.Sessions), err)
	}
	res2, err := List(root, `D:\p`, "", 2, 2)
	if err != nil || len(res2.Sessions) != 2 {
		t.Fatalf("page2: len=%d err=%v", len(res2.Sessions), err)
	}
	if res.Sessions[1].ID == res2.Sessions[0].ID {
		t.Error("page2 overlaps page1")
	}
	res3, _ := List(root, `D:\p`, "", 2, 4)
	if len(res3.Sessions) != 1 {
		t.Fatalf("last page len = %d, want 1", len(res3.Sessions))
	}
	res4, _ := List(root, `D:\p`, "", 2, 9)
	if len(res4.Sessions) != 0 || res4.Total != 5 {
		t.Fatalf("beyond-range: len=%d total=%d", len(res4.Sessions), res4.Total)
	}
}

